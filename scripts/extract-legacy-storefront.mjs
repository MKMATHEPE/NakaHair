import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const sourcePath = path.join(projectRoot, "legacy", "index.html");
const outputDirectory = path.join(projectRoot, "public", "scripts");
const outputPath = path.join(outputDirectory, "storefront.js");
const source = readFileSync(sourcePath, "utf8");
const inlineScripts = [...source.matchAll(/<script>([\s\S]*?)<\/script>/gi)];
const applicationScript = inlineScripts.at(-1)?.[1];

if (!applicationScript) {
  throw new Error("Unable to find the storefront application script.");
}

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(
  outputPath,
  `// Generated from legacy/index.html. Do not edit this file directly.\n${applicationScript.trim()}\n`,
);
